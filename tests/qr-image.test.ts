import { describe, it, expect } from "vitest";
import { qrImage } from "@/lib/security/qr-image";
const svg = '<?xml version="1.0"?>\n<!-- Generated by SVGo -->\n<svg width="10" height="10" xmlns="http://www.w3.org/2000/svg"><rect fill="#000" width="1" height="1"/></svg>';
const decode = (url: string) =>
  Buffer.from(url.replace("data:image/svg+xml;base64,", ""), "base64").toString();
describe("TOTP QR image encoding", () => {
  it("turns raw SVG from Supabase Auth into a base64 image URL", () => {
    const url = qrImage(svg)!;
    expect(url).toMatch(/^data:image\/svg\+xml;base64,/);
    expect(decode(url)).toBe(svg);
  });
  it("accepts unescaped and URL-encoded SVG data URLs, and base64 ones unchanged", () => {
    expect(decode(qrImage(`data:image/svg+xml;utf-8,${svg}`)!)).toBe(svg);
    expect(decode(qrImage(`data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`)!)).toBe(svg);
    const b64 = `data:image/svg+xml;base64,${Buffer.from(svg).toString("base64")}`;
    expect(qrImage(b64)).toBe(b64);
  });
  it("rejects anything that is not an SVG image", () => {
    for (const bad of [undefined, 42, "", "<html><script>x</script></html>", "javascript:alert(1)", "data:text/html,<svg>"])
      expect(qrImage(bad)).toBeUndefined();
    expect(qrImage(`<svg>${"x".repeat(2_000_001)}</svg>`)).toBeUndefined();
  });
});
